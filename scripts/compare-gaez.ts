/**
 * Writes docs/gaez-comparison.md: our verdict next to FAO GAEZ for every crop
 * in the five demo towns, flagging the strong disagreements for the agronomy
 * review. Offline: uses the saved snapshots, the soil grid and the GAEZ grid.
 *
 * Run with `bun gaez:compare` after changing crops.json.
 */
import snapshots from "@/../data/snapshots.json";
import towns from "@/../data/towns.json";
import { gaez_at } from "@/lib/gaez";
import type { climate } from "@/lib/power";
import { next_onset, score } from "@/lib/scorer";
import { soil_at } from "@/lib/soil";
import { Service as Crops } from "@/modules/crops/service";
import { DEMO_TOWNS } from "@/modules/recommend/site";

const saved = snapshots as Record<string, climate>;
const months = [
  "Jan",
  "Feb",
  "Mar",
  "Apr",
  "May",
  "Jun",
  "Jul",
  "Aug",
  "Sep",
  "Oct",
  "Nov",
  "Dec",
];

// Strong disagreement: we say good where GAEZ finds it marginal or worse
// (under 25), or we say poor where GAEZ finds it at least medium (40+).
const flag = (verdict: string, gaez: number | null) =>
  gaez == null
    ? ""
    : verdict === "good" && gaez < 25
      ? "⚠ we're more optimistic"
      : verdict === "poor" && gaez >= 40
        ? "⚠ we're more pessimistic"
        : "";

let md = `# Our scores against FAO GAEZ

Generated by \`bun gaez:compare\` on ${new Date().toISOString().slice(0, 10)}. Climate: saved NASA POWER snapshots (2014–2023). Soil: SoilGrids grid. Annual crops planted at the main rainy-season onset. GAEZ: suitability index 0–100 (1981–2010, rain-fed, low input); no data for cashew or rubber, banana stands in for plantain.

GAEZ low-input indices run lower than ours by design, so compare the **ranking within a town**, and look hardest at the ⚠ rows: we say *good* where GAEZ is under 25, or *poor* where GAEZ is 40 or more.
`;

let flagged = 0;
for (const name of DEMO_TOWNS) {
  const town = towns.find((t) => t.name === name)!;
  const climate = saved[name]!;
  const soil = soil_at(town.lat, town.lon)!;
  const planting = next_onset(climate.rain, 1);
  const annual = Math.round(climate.rain.reduce((a, b) => a + b, 0));

  md += `\n## ${name}\n\n${annual} mm/yr, ${climate.rain.filter((mm) => mm < 50).length} dry months, ${soil.texture.replace("_", " ")} soil, pH ${soil.ph}. Planting: ${months[planting - 1]}.\n\n`;
  md += "| Crop | Our score | Our verdict | GAEZ | Weakest factor | Flag |\n";
  md += "| --- | ---: | --- | ---: | --- | --- |\n";

  const rows = Crops.list()
    .map((crop) => ({
      crop,
      result: score(
        crop,
        {
          rain: climate.rain,
          tmean: climate.tmean,
          ph: soil.ph,
          texture: soil.texture,
        },
        planting,
        false,
      ),
      gaez: gaez_at(crop.id, town.lat, town.lon),
    }))
    .sort((a, b) => b.result.score - a.result.score);

  for (const { crop, result, gaez } of rows) {
    const weakest = [...result.factors].sort((a, b) => a.score - b.score)[0]!;
    const note = flag(result.verdict, gaez);
    if (note) flagged++;
    md += `| ${crop.name.en} | ${result.score} | ${result.verdict} | ${gaez ?? "–"} | ${weakest.key} ${weakest.value} (${weakest.score}) | ${note} |\n`;
  }
}

md += `\n${flagged} strong disagreements.\n`;
await Bun.write("docs/gaez-comparison.md", md);
console.log(`wrote docs/gaez-comparison.md (${flagged} flagged)`);
